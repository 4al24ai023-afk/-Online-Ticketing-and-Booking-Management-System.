import express, { Request, Response } from 'express';
import { createServer as createViteServer } from 'vite';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import crypto from 'crypto';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
app.use(express.json());

const PORT = process.env.PORT || 3000;
const SECRET_SALT = 'smartticket_secure_salt_2026';

app.get('/api/health', (_req: Request, res: Response) => {
  res.json({
    status: 'online',
    system: 'SMARTTICKET Backend API',
    problemStatement: 'PS-07: Online Ticketing and Booking Management System',
    timestamp: new Date().toISOString()
  });
});

async function start() {
  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(Number(PORT), '0.0.0.0', () => {
    console.log(`SMARTTICKET Server online on http://localhost:${PORT}`);
  });
}

start().catch(console.error);